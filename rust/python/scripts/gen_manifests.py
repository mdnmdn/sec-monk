"""Write modules/<name>.toml from the contract examples (rust/contracts/examples/module/py-*.json), checking that the
`provides` of each equals what the module itself announces. Run: uv run python scripts/gen_manifests.py"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EX = ROOT.parent / "contracts" / "examples" / "module"


def val(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(val(x) for x in v) + "]"
    raise TypeError(v)


def toml(d: dict) -> str:
    out = [f"{k} = {val(v)}" for k, v in d.items() if not isinstance(v, dict) and not _tables(v)]
    for k, v in d.items():
        if isinstance(v, dict):
            out += ["", f"[{k}]"] + [f"{a} = {val(b)}" for a, b in v.items() if not _tables(b)]
            for a, b in v.items():
                for item in b if _tables(b) else []:
                    out += ["", f"[[{k}.{a}]]"] + [f"{x} = {val(y)}" for x, y in item.items()]
    return "\n".join(out) + "\n"


def _tables(v) -> bool:
    return isinstance(v, list) and bool(v) and isinstance(v[0], dict)


def main() -> None:
    from secmonk_modules.registry import MODULE_NAMES, load_module

    for name in MODULE_NAMES:
        m = json.loads((EX / f"{name}.json").read_text())
        mod = load_module(name)
        assert sorted(m["provides"]["methods"]) == mod.provides()["methods"], name
        live = mod.provides()                  # collectors / sources come from the registry: the package is the truth
        for key in ("collectors", "sources", "sync_all_order"):
            if key in live:
                if m["provides"].get(key) != live[key]:
                    print(f"  note: {name} {key} differ from the contract example (registry wins)")
                m["provides"][key] = live[key]
        if name == "py-procmon":
            m["platforms"] = ["macos", "linux"]       # the process monitor has no Windows backend
        text = f"# Manifest secmonk-module/1 (generated by scripts/gen_manifests.py from the contract example)\n{toml(m)}"
        (ROOT / "modules" / f"{name}.toml").write_text(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
